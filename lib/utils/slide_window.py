import math
import torch
from torch import nn
from typing import Literal
from torch.nn import functional as F
from torch import Tensor


class SlideWindowCropper(nn.Module):
    """Utility for sliding-window crop and merge.

    Design goals:
    1) Generate sliding-window crops and record their bounding boxes on original image coordinates.
    2) Merge per-crop feature maps/logits back to one full feature map by overlap averaging.

    Notes:
    - `scale_level` controls multi-scale grid partitioning.
      For example, (1,3) means 1x1 + 2x2 + 3x3 grids, resulting in 14 crops.
    - For multi-scale crop, crop sizes are usually different across levels.
      If you need to stack all crops into one tensor, set `target_size` to a fixed size.
    - Merge infers source image extent from bbox min/max corners and projects to `target_size`.
    """

    def __init__(
        self,
        *,
        scale_level: list[int] = [3],
        overlap_ratio: float = 0.33,
        patch_size: tuple[int, int],
        interpolate_mode: Literal["bilinear", "nearest"] = "bilinear",
    ):
        super().__init__()
        assert min(scale_level) >= 1, f"Invalid scale_leve={scale_level}, Expected with positive values."
        assert 0.0 <= overlap_ratio < 1.0, f"Invalid overlap_ratio={overlap_ratio}. Expected in [0, 1)."
        assert interpolate_mode in {
            "bilinear",
            "nearest",
        }, f"Unsupported interpolate_mode={interpolate_mode}. Use 'bilinear' or 'nearest'."
        assert (
            len(patch_size) == 2 and patch_size[0] > 0 and patch_size[1] > 0
        ), f"Invalid patch_size={patch_size}. Expected (H_patch, W_patch) with positive values."

        self.scale_level = scale_level
        self.overlap_ratio = overlap_ratio
        self.patch_size = patch_size
        self.interpolate_mode = interpolate_mode

    def _interpolate(self, x: Tensor, size: tuple[int, int]) -> Tensor:
        return F.interpolate(
            x,
            size=size,
            mode=self.interpolate_mode,
            align_corners=False if self.interpolate_mode != "nearest" else None,
        )

    def make_bboxes(self, image_size: tuple[int, int]) -> list[tuple[int, int, int, int]]:
        """Generate level-controlled sliding-window bboxes in (y1, x1, y2, x2).

        Design:
        - `scale_level=(a, b)` generates bboxes for each level in [a, b].
        - Each `level=L` produces exactly `L x L` windows.
        - `L=1` always returns a single full-image window.
        - `overlap_ratio` controls window size by:
            patch = image / (1 + (L - 1) * (1 - overlap_ratio))
          and starts are evenly spaced from 0 to (image - patch), so the last
          window touches the image boundary.
        """
        h_img, w_img = image_size
        bboxes: list[tuple[int, int, int, int]] = []

        for level in self.scale_level:
            if level == 1:
                bboxes.append((0, 0, h_img, w_img))
                continue

            # Solve patch size from desired number of windows and overlap.
            # For example: H=448, level=3, overlap=0.5 -> patch=224, starts=[0,112,224].
            h_patch = int(round(h_img / (1.0 + (level - 1) * (1.0 - self.overlap_ratio))))
            w_patch = int(round(w_img / (1.0 + (level - 1) * (1.0 - self.overlap_ratio))))
            h_patch = max(1, min(h_patch, h_img))
            w_patch = max(1, min(w_patch, w_img))

            h_start_max = max(0, h_img - h_patch)
            w_start_max = max(0, w_img - w_patch)

            # Generate exactly `level` starts per axis, aligned to image borders.
            y_starts = [int(round(i * h_start_max / (level - 1))) for i in range(level)]
            x_starts = [int(round(i * w_start_max / (level - 1))) for i in range(level)]

            for y1 in y_starts:
                for x1 in x_starts:
                    y2 = min(y1 + h_patch, h_img)
                    x2 = min(x1 + w_patch, w_img)
                    if y2 > y1 and x2 > x1:
                        bboxes.append((y1, x1, y2, x2))

        return bboxes

    def crop(
        self,
        image: Tensor,
        bboxes: list[tuple[int, int, int, int]] | None = None,
    ) -> tuple[Tensor, list[tuple[int, int, int, int]]]:
        """Crop image into sliding-window patches.

        Args:
            image: [B, C, H, W]
            bboxes:
                Optional bbox list in original image coordinates.
                If omitted, bboxes are generated by `make_bboxes`.

        Returns:
            patches: [K, B, C, H_patch, W_patch]
            bboxes: length-K bbox list in original image coordinates K * (y1, x1, y2, x2)
        """
        assert image.dim() == 4, f"image must be [B, C, H, W], got shape={tuple(image.shape)}"

        H_patch, W_patch = self.patch_size
        _, channels, h_img, w_img = image.shape
        bboxes = self.make_bboxes((h_img, w_img)) if bboxes is None else bboxes
        assert len(bboxes) > 0, "No sliding-window bboxes generated."

        patch_list = [
            self._interpolate(image[:, :, y1:y2, x1:x2], size=(H_patch, W_patch)) for y1, x1, y2, x2 in bboxes
        ]  # K * [B, C, H_patch, W_patch]
        # patches = torch.stack(patch_list, dim=0).view(
        #     -1, channels, patch_list[0].shape[-2], patch_list[0].shape[-1]
        # )  # [K*B, C, H_patch, W_patch]
        patches = torch.stack(patch_list, dim=0)

        return patches, bboxes

    def merge(
        self,
        feats: Tensor,
        bboxes: list[tuple[int, int, int, int]],
        target_size: tuple[int, int] | None = None,
    ) -> Tensor:
        """Merge window feature maps to one full feature map.

        Args:
            feats: [K, B, H_feat, W_feat, C]
            bboxes: K bbox tuples in original image coordinates.
            target_size:
                (H_out, W_out) of merged output feature map.
                If None, infer output size from `feats` and `bboxes`.

        Returns:
            merged feature map: [B, H_out, W_out, C]

        Behavior:
        - Infer source image size from bboxes by min/max corners (assuming bboxes cover source image).
        - Build a single scale from inferred source size -> target_size.
        - Each crop feature map is resized to its projected bbox size on output grid.
        - Overlapped regions are averaged.
        """
        assert feats.dim() == 5, f"feats must be 5D [K,B,H,W,C], got shape={tuple(feats.shape)}"
        assert len(bboxes) == feats.shape[0], f"len(bboxes)={len(bboxes)} must equal K={feats.shape[0]}"
        assert len(bboxes) > 0, "bboxes must not be empty."
        if target_size is not None:
            assert target_size[0] > 0 and target_size[1] > 0, f"Invalid target_size={target_size}"

        _, batch_size, h_feat, w_feat, channels = feats.shape

        y_min = min(y1 for (y1, _, _, _) in bboxes)
        x_min = min(x1 for (_, x1, _, _) in bboxes)
        y_max = max(y2 for (_, _, y2, _) in bboxes)
        x_max = max(x2 for (_, _, _, x2) in bboxes)
        h_src = y_max - y_min
        w_src = x_max - x_min
        assert h_src > 0 and w_src > 0, f"Invalid inferred source size from bboxes: {(h_src, w_src)}"

        if target_size is None:
            # Infer one global feature-to-image scale from all bboxes.
            scale_y_all = [h_feat / float(y2 - y1) for (y1, _, y2, _) in bboxes]
            scale_x_all = [w_feat / float(x2 - x1) for (_, x1, _, x2) in bboxes]
            scale_y = float(sum(scale_y_all) / len(scale_y_all))
            scale_x = float(sum(scale_x_all) / len(scale_x_all))
            h_out = int(math.ceil(h_src * scale_y))
            w_out = int(math.ceil(w_src * scale_x))
        else:
            h_target, w_target = target_size
            scale_y = h_target / float(h_src)
            scale_x = w_target / float(w_src)
            h_out = h_target
            w_out = w_target

        merged = torch.zeros((batch_size, h_out, w_out, channels), device=feats.device, dtype=feats.dtype)
        counts = torch.zeros((batch_size, h_out, w_out, 1), device=feats.device, dtype=feats.dtype)

        for (y1, x1, y2, x2), feat in zip(bboxes, feats):
            yy1 = int((y1 - y_min) * scale_y)
            xx1 = int((x1 - x_min) * scale_x)
            yy2 = int(math.ceil((y2 - y_min) * scale_y))
            xx2 = int(math.ceil((x2 - x_min) * scale_x))

            yy1, xx1 = max(yy1, 0), max(xx1, 0)
            yy2, xx2 = min(yy2, h_out), min(xx2, w_out)
            if yy2 <= yy1 or xx2 <= xx1:
                continue

            target_h, target_w = yy2 - yy1, xx2 - xx1
            feat_resized = self._interpolate(feat.permute(0, 3, 1, 2), size=(target_h, target_w)).permute(0, 2, 3, 1)

            merged[:, yy1:yy2, xx1:xx2, :] += feat_resized
            counts[:, yy1:yy2, xx1:xx2, :] += 1

        assert not (counts == 0).any(), "Found uncovered pixels when merging slide-window features."

        merged = merged / counts
        return merged

    def __call__(self, image: Tensor) -> Tensor:
        """Crop image into sliding-window patches.

        Args:
            image: [B, C, H, W]
            patch_size: (H_patch, W_patch)

        Returns:
            patches: [K, B, C, H_patch, W_patch]
        """
        patches, bboxes = self.crop(image[None, :])
        return patches.squeeze_(1)
